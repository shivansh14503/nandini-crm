const OPPORTUNITIES_STORAGE_KEY = 'nandini_crm_opportunities_data_v1';

export function getStoredOpportunities(): Opportunity[] {
    if (typeof window === 'undefined') return INITIAL_MOCK_OPPORTUNITIES;
    try {
        const item = localStorage.getItem(OPPORTUNITIES_STORAGE_KEY);
        if (!item) {
            localStorage.setItem(OPPORTUNITIES_STORAGE_KEY, JSON.stringify(INITIAL_MOCK_OPPORTUNITIES));
            return INITIAL_MOCK_OPPORTUNITIES;
        }
        const parsed = JSON.parse(item);
        if (Array.isArray(parsed) && parsed.length > 0) {
            return parsed;
        }
    } catch {
        // Fallback
    }
    return INITIAL_MOCK_OPPORTUNITIES;
}

export function saveStoredOpportunities(opps: Opportunity[]) {
    if (typeof window === 'undefined') return;
    try {
        localStorage.setItem(OPPORTUNITIES_STORAGE_KEY, JSON.stringify(opps));
    } catch (e) {
        console.error('Failed to save opportunities to localStorage', e);
    }
}

export function getStoredOpportunityById(id: string): Opportunity | undefined {
    const list = getStoredOpportunities();
    return list.find((opp) => opp.id === id);
}

export function addStoredOpportunity(data: OpportunityFormData): Opportunity {
    const list = getStoredOpportunities();
    const nextSeq = list.length + 1001;
    const newOpp: Opportunity = {
        ...data,
        id: `opp-${nextSeq}`,
        opportunityCode: `OPP-${nextSeq}`,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
        createdBy: data.assignedTo || 'mittal.sharma',
    };
    const updatedList = [newOpp, ...list];
    saveStoredOpportunities(updatedList);
    return newOpp;
}

export function updateStoredOpportunity(id: string, updates: Partial<OpportunityFormData>): Opportunity | null {
    const list = getStoredOpportunities();
    const idx = list.findIndex((opp) => opp.id === id);
    if (idx === -1) return null;
    const updated: Opportunity = {
        ...list[idx],
        ...updates,
        updatedAt: new Date().toISOString(),
    };
    list[idx] = updated;
    saveStoredOpportunities(list);
    return updated;
}

export function deleteStoredOpportunity(id: string): boolean {
    const list = getStoredOpportunities();
    const filtered = list.filter((opp) => opp.id !== id);
    if (filtered.length !== list.length) {
        saveStoredOpportunities(filtered);
        return true;
    }
    return false;
}

export function deleteMultipleStoredOpportunities(ids: string[]): boolean {
    const idSet = new Set(ids);
    const list = getStoredOpportunities();
    const filtered = list.filter((opp) => !idSet.has(opp.id));
    saveStoredOpportunities(filtered);
    return true;
}
