import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Copies the PDF document model (src/modules/pdf/document, minus tests) into frontend-crm/src/lib/pdf-document so
 * the builder canvas renders blocks with exactly the code the server prints with. Run `npm run sync:pdf-document`
 * after changing those files; contractSync.test.ts fails while the copies differ.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
export const DOCUMENT_SRC = path.resolve(here, '../src/modules/pdf/document');
export const DOCUMENT_DEST = path.resolve(here, '../../frontend-crm/src/lib/pdf-document');

const HEADER = '// GENERATED by backend-crm `npm run sync:pdf-document` from src/modules/pdf/document. Do not edit here.\n';

/** `{ fileName: content }` the frontend copy must contain. Relative `./x.js` imports become `./x` for the bundler. */
export function expectedFrontendFiles(): Record<string, string> {
    const files: Record<string, string> = {};
    for (const name of readdirSync(DOCUMENT_SRC).sort()) {
        if (!name.endsWith('.ts') || name.endsWith('.test.ts')) continue;
        const source = readFileSync(path.join(DOCUMENT_SRC, name), 'utf8').replace(/(from\s+'\.\/[\w-]+)\.js'/g, "$1'");
        files[name] = HEADER + source;
    }
    return files;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    mkdirSync(DOCUMENT_DEST, { recursive: true });
    const expected = expectedFrontendFiles();
    for (const name of readdirSync(DOCUMENT_DEST)) {
        if (!(name in expected)) console.warn(`Unexpected file in ${DOCUMENT_DEST}: ${name} (remove it if obsolete)`);
    }
    for (const [name, content] of Object.entries(expected)) writeFileSync(path.join(DOCUMENT_DEST, name), content);
    console.log(`Synced ${Object.keys(expected).length} files to ${DOCUMENT_DEST}`);
}
