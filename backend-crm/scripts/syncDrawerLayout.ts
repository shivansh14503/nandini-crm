import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Copies the drawer layout model (src/modules/drawer-layouts/document, minus tests) into
 * frontend-crm/src/lib/drawer-layout so the builder and the drawers validate layouts with exactly the code the API
 * saves them with. Run `npm run sync:drawer-layout` after changing those files; contractSync.test.ts fails while the
 * copies differ.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
export const DRAWER_LAYOUT_SRC = path.resolve(here, '../src/modules/drawer-layouts/document');
export const DRAWER_LAYOUT_DEST = path.resolve(here, '../../frontend-crm/src/lib/drawer-layout');

const HEADER = '// GENERATED by backend-crm `npm run sync:drawer-layout` from src/modules/drawer-layouts/document. Do not edit here.\n';

/** `{ fileName: content }` the frontend copy must contain. Relative `./x.js` imports become `./x` for the bundler. */
export function expectedDrawerLayoutFiles(): Record<string, string> {
    const files: Record<string, string> = {};
    for (const name of readdirSync(DRAWER_LAYOUT_SRC).sort()) {
        if (!name.endsWith('.ts') || name.endsWith('.test.ts')) continue;
        const source = readFileSync(path.join(DRAWER_LAYOUT_SRC, name), 'utf8').replace(/(from\s+'\.\/[\w-]+)\.js'/g, "$1'");
        files[name] = HEADER + source;
    }
    return files;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    mkdirSync(DRAWER_LAYOUT_DEST, { recursive: true });
    const expected = expectedDrawerLayoutFiles();
    for (const name of readdirSync(DRAWER_LAYOUT_DEST)) {
        if (!(name in expected)) console.warn(`Unexpected file in ${DRAWER_LAYOUT_DEST}: ${name} (remove it if obsolete)`);
    }
    for (const [name, content] of Object.entries(expected)) writeFileSync(path.join(DRAWER_LAYOUT_DEST, name), content);
    console.log(`Synced ${Object.keys(expected).length} files to ${DRAWER_LAYOUT_DEST}`);
}
