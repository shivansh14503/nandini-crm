import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Copies the company display-formats core (src/modules/company-formats/core, minus tests) into
 * frontend-crm/src/lib/display-formats so screens format dates, times and numbers with exactly the code the PDFs,
 * emails and notifications use. Run `npm run sync:display-formats` after changing those files; contractSync.test.ts
 * fails while the copies differ.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
export const DISPLAY_FORMATS_SRC = path.resolve(here, '../src/modules/company-formats/core');
export const DISPLAY_FORMATS_DEST = path.resolve(here, '../../frontend-crm/src/lib/display-formats');

const HEADER = '// GENERATED by backend-crm `npm run sync:display-formats` from src/modules/company-formats/core. Do not edit here.\n';

/** `{ fileName: content }` the frontend copy must contain. Relative `./x.js` imports become `./x` for the bundler. */
export function expectedDisplayFormatsFiles(): Record<string, string> {
    const files: Record<string, string> = {};
    for (const name of readdirSync(DISPLAY_FORMATS_SRC).sort()) {
        if (!name.endsWith('.ts') || name.endsWith('.test.ts')) continue;
        const source = readFileSync(path.join(DISPLAY_FORMATS_SRC, name), 'utf8').replace(/(from\s+'\.\/[\w-]+)\.js'/g, "$1'");
        files[name] = HEADER + source;
    }
    return files;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    mkdirSync(DISPLAY_FORMATS_DEST, { recursive: true });
    const expected = expectedDisplayFormatsFiles();
    for (const name of readdirSync(DISPLAY_FORMATS_DEST)) {
        if (!(name in expected)) console.warn(`Unexpected file in ${DISPLAY_FORMATS_DEST}: ${name} (remove it if obsolete)`);
    }
    for (const [name, content] of Object.entries(expected)) writeFileSync(path.join(DISPLAY_FORMATS_DEST, name), content);
    console.log(`Synced ${Object.keys(expected).length} files to ${DISPLAY_FORMATS_DEST}`);
}
