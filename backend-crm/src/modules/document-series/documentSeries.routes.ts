import { Router, type Request, type Response } from 'express';
import { authenticate, requireRole } from '../../middlewares/authMiddleware.js';
import { sendSuccess } from '../../utils/apiResponse.js';
import { requireUser } from '../../utils/requestContext.js';
import { FORM_CONFIG_ADMIN_ROLES } from '../form-configs/formConfig.routes.js';
import { documentSeriesService } from './documentSeries.service.js';

/**
 * /api/document-series   (admin only)
 *   GET  /   global settings, every module's rules, the current financial year and each module's next number
 *   PUT  /   { companyPrefix, separator, fyStartMonth, fyFormat, series: [{ module, modulePrefix, ... }] }
 *
 * Numbers are generated by `generateDocumentCode` (documentSeries.service.ts) when a record is created.
 */
const router = Router();
router.use(authenticate, requireRole(...FORM_CONFIG_ADMIN_ROLES));

router.get('/', async (_req: Request, res: Response) => {
    sendSuccess(res, await documentSeriesService.getConfig());
});

router.put('/', async (req: Request, res: Response) => {
    sendSuccess(res, await documentSeriesService.saveConfig(req.body, requireUser(req)), 'Document series saved');
});

export default router;
